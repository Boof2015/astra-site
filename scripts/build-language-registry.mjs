// Generates docs/xlrcdb/language-registry.js from Node's ICU data.
//
// xlrcdb's CI validates language tags with Intl.DisplayNames in Node (full ICU). Browsers ship
// much less: Chrome knows ~350 languages to Node's ~930, so a browser-side Intl check would
// reject tags CI accepts ("kr", "haw" on some builds). The editor validates against this
// snapshot instead. Regenerate when the data repo's Node version changes:
//
//   npm run build:languages

import { writeFile } from "node:fs/promises";

const OUTPUT = new URL("../docs/xlrcdb/language-registry.js", import.meta.url);
const LETTERS = "abcdefghijklmnopqrstuvwxyz";

const languageNames = new Intl.DisplayNames(["en"], { type: "language", fallback: "none" });
const scriptNames = new Intl.DisplayNames(["en"], { type: "script", fallback: "none" });
const regionNames = new Intl.DisplayNames(["en"], { type: "region", fallback: "none" });

function nameOf(displayNames, code) {
  try {
    return displayNames.of(code) || "";
  } catch {
    return "";
  }
}

function* combos(length) {
  if (length === 0) {
    yield "";
    return;
  }
  for (const prefix of combos(length - 1)) for (const letter of LETTERS) yield prefix + letter;
}

const languages = {};
for (const length of [2, 3]) {
  for (const code of combos(length)) {
    const name = nameOf(languageNames, code);
    if (name) languages[code] = name;
  }
}

const scripts = [];
for (const code of combos(4)) {
  const script = code[0].toUpperCase() + code.slice(1);
  if (nameOf(scriptNames, script)) scripts.push(script);
}

const regions = [];
for (const code of combos(2)) {
  if (nameOf(regionNames, code.toUpperCase())) regions.push(code.toUpperCase());
}
for (let i = 0; i < 1000; i++) {
  const code = String(i).padStart(3, "0");
  if (nameOf(regionNames, code)) regions.push(code);
}

const source = `// Generated by scripts/build-language-registry.mjs from Node ${process.version} (ICU ${process.versions.icu}).
// Do not edit by hand; run \`npm run build:languages\`.

export const LANGUAGES = ${JSON.stringify(languages)};

export const SCRIPTS = ${JSON.stringify(scripts)};

export const REGIONS = ${JSON.stringify(regions)};
`;

await writeFile(OUTPUT, source);
console.log(`language-registry.js: ${Object.keys(languages).length} languages, ${scripts.length} scripts, ${regions.length} regions`);
